  SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
  ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

  update_count() {
    local file="$1"
    local old_pattern="$2"
    local new_text="$3"
    if [ -f "$file" ]; then
      sed -i "s/$old_pattern/$new_text/g" "$file" 2>/dev/null || true
    fi
