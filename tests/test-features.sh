  update_count "$ROOT/DOCS.md"          "[0-9]\+ tests passing"                 "$TOTAL tests passing"
  update_count "$ROOT/CONTRIBUTING.md"  "[0-9]\+ tests\. All must"              "$TOTAL tests. All must"

