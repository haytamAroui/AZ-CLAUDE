#!/bin/bash

PASS=0
FAIL=0
ERRORS=""

check() {
  local desc="$1"
  local file="$2"
  local pattern="$3"

  if grep -qi "$pattern" "$file" 2>/dev/null; then
    echo "  ✓ $desc"
    PASS=$((PASS + 1))
  else
    echo "  ✗ $desc"
    ERRORS="$ERRORS\n  FAILED: $desc\n    File: $file\n    Pattern: $pattern"
    FAIL=$((FAIL + 1))
  fi
}

check_file() {
  local desc="$1"
  local file="$2"
  if [ -f "$file" ]; then
    echo "  ✓ $desc"
    PASS=$((PASS + 1))
  else
    echo "  ✗ $desc"
    ERRORS="$ERRORS\n  FAILED: $desc\n    File missing: $file"
    FAIL=$((FAIL + 1))
  fi
}

check_absent() {
  local desc="$1"
  local file="$2"
  local pattern="$3"
  if ! grep -qi "$pattern" "$file" 2>/dev/null; then
    echo "  ✓ $desc"
    PASS=$((PASS + 1))
  else
    echo "  ✗ $desc"
    ERRORS="$ERRORS\n  FAILED: $desc\n    File: $file\n    Pattern present (should be absent): $pattern"
    FAIL=$((FAIL + 1))
  fi
}

